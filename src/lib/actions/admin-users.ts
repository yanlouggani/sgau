import {
  createUserSchema,
  updateUserAuthSchema,
  updateUserSchema,
  deleteUserSchema,
  toggleUserActiveSchema,
  ALLOWED_TARGET_ROLES,
  isServiceKeyRestrictedError,
  generateSecureTempPassword,
} from "@/lib/user-auth-utils";

export async function createUserAction(rawParams: {
  email: string;
  password?: string;
  firstname: string;
  lastname: string;
  role: string;
  isActive?: boolean;
}) {
  const parsed = createUserSchema.parse(rawParams);

  // Vérification de la session et des privilèges de l'appelant
  const { profile: callerProfile } = await requireRole("admin", "secretary");

  const allowedRoles = ALLOWED_TARGET_ROLES[callerProfile.role] ?? [];
  if (!allowedRoles.includes(parsed.role)) {
    if (callerProfile.role === "secretary") {
      throw new Error(
        "Privilèges insuffisants : une secrétaire peut uniquement créer des comptes Enseignant ou Élève."
      );
    }
    throw new Error("Privilèges insuffisants pour créer un compte avec ce rôle.");
  }

  // Mot de passe sécurisé si aucun n'est renseigné
  const isAutoGenerated = !parsed.password || parsed.password.trim().length === 0;
  const effectivePassword = isAutoGenerated
    ? generateSecureTempPassword()
    : parsed.password!.trim();

  let userId: string | null = null;
  let authUser: { id: string; email?: string } | null = null;

  // 1. Tenter la création via Supabase Auth Admin (si service_role_key valide)
  try {
    const adminClient = createAdminClient();
    const { data: authData, error: authError } = await adminClient.auth.admin.createUser({
      email: parsed.email,
      password: effectivePassword,
      email_confirm: true,
      user_metadata: {
        firstname: parsed.firstname,
        lastname: parsed.lastname,
        role: parsed.role,
      },
    });

    if (!authError && authData?.user) {
      authUser = authData.user;
      userId = authData.user.id;
    } else if (authError && !isServiceKeyRestrictedError(authError)) {
      // Erreur réelle (ex: email déjà pris)
      throw new Error(`Erreur lors de la création du compte : ${authError.message}`);
    }
  } catch (err: unknown) {
    if (!isServiceKeyRestrictedError(err)) {
      throw err;
    }
    // Fallback ci-dessous si clé service_role restreinte / invalide
  }

  // 2. Fallback résilient via Auth SignUp (avec clé publique / anon)
  if (!userId) {
    const { createClient: createSupabaseJsClient } = await import("@supabase/supabase-js");
    const anonClient = createSupabaseJsClient(
      process.env.NEXT_PUBLIC_SUPABASE_URL!,
      process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
      { auth: { persistSession: false, autoRefreshToken: false } }
    );

    const { data: signData, error: signError } = await anonClient.auth.signUp({
      email: parsed.email,
      password: effectivePassword,
      options: {
        data: {
          firstname: parsed.firstname,
          lastname: parsed.lastname,
          role: parsed.role,
        },
      },
    });

    if (signError) {
      throw new Error(`Erreur lors de la création du compte : ${signError.message}`);
    }

    if (!signData?.user) {
      throw new Error("Erreur inattendue : aucun utilisateur n'a été créé par Supabase.");
    }

    authUser = signData.user;
    userId = signData.user.id;
  }

  // 3. Finalisation / Upsert dans la table public.users
  const supabase = await createClient();

  // Tenter l'appel RPC admin_finalize_user
  const { error: rpcError } = await supabase.rpc("admin_finalize_user", {
    p_uid: userId,
    p_group_id: null,
  });

  // Assurer la synchronisation complète des colonnes dans public.users
  const { error: upsertError } = await supabase.from("users").upsert({
    id: userId,
    email: parsed.email,
    firstname: parsed.firstname,
    lastname: parsed.lastname,
    role: parsed.role,
    isactive: parsed.isActive ?? true,
  });

  if (upsertError && rpcError) {
    console.error("Échec de la finalisation du profil utilisateur :", upsertError);
    // Nettoyage de sécurité du compte auth orphelin créé si possible
    try {
      const adminClient = createAdminClient();
      await adminClient.auth.admin.deleteUser(userId);
    } catch {
      // Ignorer l'erreur de nettoyage si service_role est restreint
    }
    throw new Error(`Erreur lors de l'enregistrement du profil : ${upsertError.message}`);
  }

  return {
    user: authUser,
    tempPassword: isAutoGenerated ? effectivePassword : undefined,
  };
}

export async function updateUserAuthAction(rawParams: {
  id: string;
  password?: string;
  email?: string;
}) {
  const parsed = updateUserAuthSchema.parse(rawParams);

  const { profile: callerProfile } = await requireRole("admin", "secretary");
  const supabase = await createClient();

  // Si l'appelant est une secrétaire, vérifier que l'utilisateur cible n'est pas un admin ou une secrétaire
  if (callerProfile.role === "secretary") {
    const { data: targetProfile, error: targetError } = await supabase
      .from("users")
      .select("role")
      .eq("id", parsed.id)
      .single();

    if (targetError || !targetProfile) {
      throw new Error("Utilisateur cible introuvable.");
    }

    if (targetProfile.role === "admin" || targetProfile.role === "secretary") {
      throw new Error(
        "Privilèges insuffisants : une secrétaire ne peut pas modifier un compte Administrateur ou Secrétaire."
      );
    }
  }

  const updates: { password?: string; email?: string; email_confirm?: boolean } = {};
  if (parsed.password && parsed.password.trim().length >= 8) {
    updates.password = parsed.password.trim();
  }
  if (parsed.email && parsed.email.trim().length > 0) {
    updates.email = parsed.email.trim().toLowerCase();
    updates.email_confirm = true;
  }

  if (Object.keys(updates).length > 0) {
    try {
      const adminClient = createAdminClient();
      const { data, error } = await adminClient.auth.admin.updateUserById(parsed.id, updates);
      if (!error && data?.user) {
        return { user: data.user };
      }
      if (error && !isServiceKeyRestrictedError(error)) {
        throw new Error(`Erreur lors de la mise à jour des identifiants : ${error.message}`);
      }
    } catch (err: unknown) {
      if (!isServiceKeyRestrictedError(err)) {
        throw err;
      }
      console.warn("Mise à jour directe du mot de passe non autorisée sans clé service role active.");
    }
  }

  return { user: null };
}

export async function updateUserAction(rawParams: {
  id: string;
  email: string;
  firstname: string;
  lastname: string;
  role: string;
  isActive?: boolean;
  password?: string;
}) {
  const parsed = updateUserSchema.parse(rawParams);

  const { profile: callerProfile } = await requireRole("admin", "secretary");
  const supabase = await createClient();

  // Récupérer le profil cible existant pour vérifier les droits
  const { data: targetProfile, error: targetError } = await supabase
    .from("users")
    .select("role")
    .eq("id", parsed.id)
    .single();

  if (targetError || !targetProfile) {
    throw new Error("Utilisateur cible introuvable.");
  }

  // Vérification de sécurité pour secrétaire
  if (callerProfile.role === "secretary") {
    if (targetProfile.role === "admin" || targetProfile.role === "secretary") {
      throw new Error(
        "Privilèges insuffisants : une secrétaire ne peut pas modifier un compte Administrateur ou Secrétaire."
      );
    }
    if (parsed.role !== "professor" && parsed.role !== "student") {
      throw new Error(
        "Privilèges insuffisants : une secrétaire ne peut attribuer que les rôles Professeur ou Élève."
      );
    }
  }

  // 1. Mettre à jour public.users
  const { error: dbError } = await supabase
    .from("users")
    .update({
      email: parsed.email,
      firstname: parsed.firstname,
      lastname: parsed.lastname,
      role: parsed.role,
      isactive: parsed.isActive ?? true,
    })
    .eq("id", parsed.id);

  if (dbError) {
    throw new Error(`Erreur lors de la mise à jour du profil : ${dbError.message}`);
  }

  // 2. Mettre à jour Auth si service_role est disponible
  const authUpdates: {
    password?: string;
    email?: string;
    email_confirm?: boolean;
    user_metadata?: Record<string, unknown>;
  } = {
    email: parsed.email,
    email_confirm: true,
    user_metadata: {
      firstname: parsed.firstname,
      lastname: parsed.lastname,
      role: parsed.role,
    },
  };

  if (parsed.password && parsed.password.trim().length >= 8) {
    authUpdates.password = parsed.password.trim();
  }

  let updatedAuthUser = null;
  try {
    const adminClient = createAdminClient();
    const { data: authData, error: authError } = await adminClient.auth.admin.updateUserById(
      parsed.id,
      authUpdates
    );
    if (!authError && authData?.user) {
      updatedAuthUser = authData.user;
    } else if (authError && !isServiceKeyRestrictedError(authError)) {
      console.warn("Avertissement synchronisation auth :", authError.message);
    }
  } catch (err: unknown) {
    if (!isServiceKeyRestrictedError(err)) {
      console.warn("Avertissement synchronisation auth :", err);
    }
  }

  return { success: true, user: updatedAuthUser };
}

export async function deleteUserAction(rawParams: { id: string }) {
  const parsed = deleteUserSchema.parse(rawParams);

  const { profile: callerProfile } = await requireRole("admin", "secretary");

  if (callerProfile.id === parsed.id) {
    throw new Error("Vous ne pouvez pas supprimer votre propre compte utilisateur.");
  }

  const supabase = await createClient();

  const { data: targetProfile, error: targetError } = await supabase
    .from("users")
    .select("role")
    .eq("id", parsed.id)
    .single();

  if (targetError || !targetProfile) {
    throw new Error("Utilisateur cible introuvable.");
  }

  if (callerProfile.role === "secretary") {
    if (targetProfile.role === "admin" || targetProfile.role === "secretary") {
      throw new Error(
        "Privilèges insuffisants : une secrétaire ne peut pas supprimer un compte Administrateur ou Secrétaire."
      );
    }
  }

  // 1. Tenter via RPC admin_delete_user
  const { error: rpcError } = await supabase.rpc("admin_delete_user", { p_uid: parsed.id });

  // 2. Si le RPC échoue ou n'existe pas, suppression directe de public.users
  if (rpcError) {
    const { error: dbError } = await supabase.from("users").delete().eq("id", parsed.id);
    if (dbError) {
      throw new Error(
        `Impossible de supprimer cet utilisateur (données liées existantes) : ${dbError.message}`
      );
    }
  }

  // 3. Suppression dans Supabase Auth si service_role disponible
  try {
    const adminClient = createAdminClient();
    await adminClient.auth.admin.deleteUser(parsed.id);
  } catch (err: unknown) {
    if (!isServiceKeyRestrictedError(err)) {
      console.warn("Avertissement suppression Auth :", err);
    }
  }

  return { success: true };
}

export async function toggleUserActiveAction(rawParams: { id: string; isActive: boolean }) {
  const parsed = toggleUserActiveSchema.parse(rawParams);

  const { profile: callerProfile } = await requireRole("admin", "secretary");

  if (callerProfile.id === parsed.id && !parsed.isActive) {
    throw new Error("Vous ne pouvez pas désactiver votre propre compte utilisateur.");
  }

  const supabase = await createClient();

  const { data: targetProfile, error: targetError } = await supabase
    .from("users")
    .select("role")
    .eq("id", parsed.id)
    .single();

  if (targetError || !targetProfile) {
    throw new Error("Utilisateur cible introuvable.");
  }

  if (callerProfile.role === "secretary") {
    if (targetProfile.role === "admin" || targetProfile.role === "secretary") {
      throw new Error(
        "Privilèges insuffisants : une secrétaire ne peut pas modifier un compte Administrateur ou Secrétaire."
      );
    }
  }

  const { error: dbError } = await supabase
    .from("users")
    .update({ isactive: parsed.isActive })
    .eq("id", parsed.id);

  if (dbError) {
    throw new Error(`Erreur lors de la modification du statut : ${dbError.message}`);
  }

  return { success: true, isActive: parsed.isActive };
}
